// Package dockerfile generates a Dockerfile that wraps a devcontainer
// base image (or upstream Dockerfile) with feature install scripts and a
// pre-staged VS Code server.
//
// The resulting Dockerfile is a single-stage build that:
//
//  1. FROM the base image (or an intermediate stage produced by an
//     upstream Dockerfile build).
//  2. Writes devcontainer-features.builtin.env (_CONTAINER_USER,
//     _REMOTE_USER and their homes) into /tmp/dev-container-features/.
//  3. For each feature in install order: sets the feature's containerEnv,
//     COPYs its contents into /tmp/dev-container-features/<safe-id>/
//     next to its devcontainer-features.env (option values) and install
//     wrapper, and RUNs the wrapper, which exports both env files and
//     runs install.sh (as upstream devcontainers/cli does).
//  4. COPY the VS Code server tarball into the canonical
//     ~/.vscode-server/bin/<commit>/ location and unpack it.
//  5. Set ENV / USER / WORKDIR according to the spec.
//
// The generator does not run the build itself; it only emits the
// Dockerfile bytes plus a list of files that must be present in the build
// context.
package dockerfile

import (
	"fmt"
	"sort"
	"strings"

	"github.com/wyrd-company/devcontainer-builder/pkg/features"
	"github.com/wyrd-company/devcontainer-builder/pkg/metadata"
	"github.com/wyrd-company/devcontainer-builder/pkg/spec"
	"github.com/wyrd-company/devcontainer-builder/pkg/vscode"
)

// Inputs collects everything the generator needs.
type Inputs struct {
	// BaseMetadata is the metadata of the FROM image, before features and config.
	BaseMetadata []metadata.Entry
	// Spec is the loaded devcontainer.json.
	Spec *spec.DevContainer
	// BaseImage is the FROM image. May be either the spec's `image`
	// field, or a tag produced by a prior build of the
	// spec's upstream Dockerfile.
	BaseImage string
	// Features in install order, all already staged on disk.
	Features []features.Resolved
	// FeaturesContextDir is the path within the build context that
	// contains the staged feature directories. Each feature is at
	// FeaturesContextDir/<SafeID>.
	FeaturesContextDir string
	// VSCodeServer optionally injects a VS Code server tarball.
	VSCodeServer *vscode.Result
	// VSCodeServerContextPath is the path within the build context to
	// the server tarball (relative to context root).
	VSCodeServerContextPath string
	// RemoteUser overrides the spec's remoteUser. Empty means use the
	// spec's value, falling back to root.
	RemoteUser string
	// ImageUser is the user configured in the base image. Features see
	// it as the container user when the spec sets no containerUser.
	// Empty means root.
	ImageUser string
}

// Generate emits the Dockerfile contents.
func Generate(in Inputs) ([]byte, error) {
	var b strings.Builder

	user := in.RemoteUser
	if user == "" {
		user = in.Spec.RemoteUser
	}
	if user == "" {
		user = in.Spec.ContainerUser
	}

	fmt.Fprintln(&b, "# syntax=docker/dockerfile:1.7")
	fmt.Fprintln(&b, "# Generated by devcontainer-builder. Do not edit by hand.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "FROM %s\n", in.BaseImage)
	fmt.Fprintln(&b)

	fmt.Fprintln(&b, "USER root")
	fmt.Fprintln(&b, "SHELL [\"/bin/sh\", \"-c\"]")
	fmt.Fprintln(&b)

	if len(in.Features) > 0 {
		fmt.Fprintln(&b, "# --- devcontainer features -------------------------------------------")
		containerUser, remoteUser := features.ContainerUsers(in.Spec.ContainerUser, user, in.ImageUser)
		emitBuiltinEnv(&b, containerUser, remoteUser)
		for _, f := range in.Features {
			emitFeature(&b, f, in.FeaturesContextDir)
		}
	}

	// The spec's containerEnv follows the features, as upstream orders it.
	if env := mapToEnv(toStringMap(in.Spec.ContainerEnv)); env != "" {
		fmt.Fprintln(&b, env)
		fmt.Fprintln(&b)
	}

	if in.VSCodeServer != nil {
		emitVSCodeServer(&b, *in.VSCodeServer, in.VSCodeServerContextPath, user)
	}

	if in.Spec.WorkspaceFolder != "" {
		fmt.Fprintf(&b, "WORKDIR %s\n", shellQuote(in.Spec.WorkspaceFolder))
	}

	if user != "" && user != "root" {
		fmt.Fprintf(&b, "USER %s\n", user)
	}

	label, err := metadata.DockerfileLabel(metadata.Collect(in.BaseMetadata, in.Features, in.Spec))
	if err != nil {
		return nil, fmt.Errorf("metadata label: %w", err)
	}
	fmt.Fprintln(&b, label)
	return []byte(b.String()), nil
}

func emitBuiltinEnv(b *strings.Builder, containerUser, remoteUser string) {
	path := features.InstallDir + "/" + features.BuiltinEnvFile
	fmt.Fprintf(b, "RUN mkdir -p %s\n", features.InstallDir)
	emitHeredocCopy(b, "", path, features.BuiltinEnvContent(containerUser, remoteUser))
	fmt.Fprintf(b, "RUN %s\n\n", features.BuiltinHomesCommand(path, containerUser, remoteUser))
}

func emitFeature(b *strings.Builder, f features.Resolved, contextDir string) {
	src := contextDir + "/" + f.SafeID
	dest := features.InstallDir + "/" + f.SafeID
	fmt.Fprintf(b, "# Feature: %s (%s)\n", f.Metadata.ID, f.Source)
	// A feature's containerEnv is visible to its own install script.
	if env := mapToEnv(f.Metadata.ContainerEnv); env != "" {
		fmt.Fprintln(b, env)
	}
	fmt.Fprintf(b, "COPY --chown=root:root %s %s\n", src, dest)
	emitHeredocCopy(b, "", dest+"/"+features.EnvFile, f.EnvFileContent())
	emitHeredocCopy(b, "--chmod=755 ", dest+"/"+features.InstallWrapperFile, f.InstallWrapperContent())
	fmt.Fprintf(b, "RUN %s && rm -rf %s\n\n", features.InstallCommand(dest), shellQuote(dest))
}

// emitHeredocCopy writes content to dest with a COPY heredoc. The quoted
// delimiter disables variable expansion, and is chosen so that no content
// line ends the heredoc early.
func emitHeredocCopy(b *strings.Builder, flags, dest, content string) {
	delim := "DEVCONTAINER_EOF"
	for n := 1; containsLine(content, delim); n++ {
		delim = fmt.Sprintf("DEVCONTAINER_EOF_%d", n)
	}
	if !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	fmt.Fprintf(b, "COPY %s<<\"%s\" %s\n%s%s\n", flags, delim, dest, content, delim)
}

func containsLine(content, line string) bool {
	for _, l := range strings.Split(content, "\n") {
		if l == line {
			return true
		}
	}
	return false
}

func emitVSCodeServer(b *strings.Builder, r vscode.Result, ctxPath, user string) {
	dir := vscode.CanonicalInstallDir(user, r.Commit)
	owner := user
	if owner == "" {
		owner = "root"
	}
	fmt.Fprintln(b, "# --- VS Code Server injection ---")
	fmt.Fprintf(b, "# Source: %s\n", r.URL)
	fmt.Fprintf(b, "# SHA256: %s  (%d bytes)\n", r.SHA256, r.Bytes)
	fmt.Fprintf(b, "COPY %s /tmp/vscode-server.tar.gz\n", ctxPath)
	fmt.Fprintf(b, "RUN set -e; mkdir -p %s && tar -xzf /tmp/vscode-server.tar.gz -C %s --strip-components=1 && rm /tmp/vscode-server.tar.gz\n",
		shellQuote(dir), shellQuote(dir))
	if owner != "root" {
		// The .vscode-server tree must be owned by the remote user so
		// VS Code's launcher can write to it at runtime.
		fmt.Fprintf(b, "RUN if id -u %s >/dev/null 2>&1; then chown -R %s:%s %s/.vscode-server || true; fi\n",
			shellQuote(owner), shellQuote(owner), shellQuote(owner), shellQuote(homeOf(owner)))
	}
	fmt.Fprintln(b)
}

func homeOf(user string) string {
	if user == "" || user == "root" {
		return "/root"
	}
	return "/home/" + user
}

func mapToEnv(m map[string]string) string {
	if len(m) == 0 {
		return ""
	}
	keys := sortedKeys(m)
	var b strings.Builder
	for _, k := range keys {
		fmt.Fprintf(&b, "ENV %s=%s\n", k, shellQuote(m[k]))
	}
	return strings.TrimRight(b.String(), "\n")
}

func toStringMap(m map[string]any) map[string]string {
	out := map[string]string{}
	for k, v := range m {
		switch t := v.(type) {
		case string:
			out[k] = t
		case nil:
			out[k] = ""
		default:
			out[k] = fmt.Sprintf("%v", v)
		}
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// shellQuote returns a single-quoted shell-safe representation, suitable
// for embedding in Dockerfile RUN/ENV lines that use sh -c.
func shellQuote(s string) string {
	if s == "" {
		return "''"
	}
	if !strings.ContainsAny(s, " \t\n\"'$`\\!*?[]{}()&;<>|#") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
